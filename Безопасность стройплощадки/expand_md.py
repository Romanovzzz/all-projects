def process_formulas(text):
    # Превращаем ** H = x ** в $$ H = x $$ если там есть = или математические знаки
    # Регулярка ищет **...**, если внутри есть = или +, -, /
    # Будем осторожны, просто заменим явно
    text = re.sub(r'\*\*(.*?=.*?)\*\*', r'$$ \1 $$', text)
    # Поправим эскейпинг в формулах типа \!
    text = text.replace(r'\!', '')
    test_re = re.compile(r'\$\$(.*?)\$\$')
    
    def repl(m):
        clean = m.group(1).replace(r'\_', '_').replace(r'\*', '*').replace('·', r'\cdot ').strip()
        # Если там нет латеха, обернем в него
        return f"$$ {clean} $$"
    
    text = test_re.sub(repl, text)
    return text

for fname in files:
    path = os.path.join(ans_dir, fname)
    if not os.path.exists(path):
        continue
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    
    # 1. Применяем текстовые правки
    for pattern, repl in corrections:
        content = re.sub(pattern, lambda m: repl.replace(r'\1', m.group(1)) if r'\1' in repl else repl, content, flags=re.DOTALL)
        
    # 2. Оборачиваем формулы
    content = process_formulas(content)
    
    # 3. Делаем параграфы более подробными (добавляем декоративные эпитеты)
    content = content.replace("### Общие положения", "### Общие положения и актуальность")
    content = content.replace("### Причины", "### Анализ основных причин")
    
    out_path = os.path.join(ans_dir, fname.replace(".md", "_v2.md"))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Processed {fname} -> {out_path}")
